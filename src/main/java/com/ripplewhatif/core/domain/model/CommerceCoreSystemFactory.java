package com.ripplewhatif.core.domain.model;

import com.ripplewhatif.core.patterns.builder.ComponentBuilder;
import com.ripplewhatif.core.patterns.builder.SystemModelBuilder;

public final class CommerceCoreSystemFactory {

    private CommerceCoreSystemFactory() {}

    public static SystemModel createCommerceCoreModel() {
        return new SystemModelBuilder()
                .id("commerce-core")
                .name("Commerce Core Architecture")
                .addComponent(ComponentBuilder.of("web-gateway", "Web Gateway")
                        .type("GATEWAY")
                        .criticality(ComponentCriticality.CRITICAL)
                        .latencyMs(40.0)
                        .availability(99.99)
                        .loadQps(1000.0)
                        .build())
                .addComponent(ComponentBuilder.of("authentication", "Authentication")
                        .type("SERVICE")
                        .criticality(ComponentCriticality.CRITICAL)
                        .latencyMs(80.0)
                        .availability(99.99)
                        .loadQps(800.0)
                        .build())
                .addComponent(ComponentBuilder.of("product-catalog", "Product Catalog")
                        .type("SERVICE")
                        .criticality(ComponentCriticality.HIGH)
                        .latencyMs(65.0)
                        .availability(99.95)
                        .loadQps(600.0)
                        .build())
                .addComponent(ComponentBuilder.of("inventory", "Inventory")
                        .type("SERVICE")
                        .criticality(ComponentCriticality.HIGH)
                        .latencyMs(50.0)
                        .availability(99.95)
                        .loadQps(400.0)
                        .build())
                .addComponent(ComponentBuilder.of("cart", "Cart")
                        .type("SERVICE")
                        .criticality(ComponentCriticality.HIGH)
                        .latencyMs(55.0)
                        .availability(99.95)
                        .loadQps(450.0)
                        .build())
                .addComponent(ComponentBuilder.of("checkout", "Checkout")
                        .type("SERVICE")
                        .criticality(ComponentCriticality.CRITICAL)
                        .latencyMs(90.0)
                        .availability(99.99)
                        .loadQps(300.0)
                        .build())
                .addComponent(ComponentBuilder.of("payment", "Payment")
                        .type("SERVICE")
                        .criticality(ComponentCriticality.CRITICAL)
                        .latencyMs(120.0)
                        .availability(99.99)
                        .loadQps(200.0)
                        .build())
                .addComponent(ComponentBuilder.of("order-service", "Order Service")
                        .type("SERVICE")
                        .criticality(ComponentCriticality.CRITICAL)
                        .latencyMs(85.0)
                        .availability(99.99)
                        .loadQps(250.0)
                        .build())
                .addComponent(ComponentBuilder.of("notification", "Notification")
                        .type("WORKER")
                        .criticality(ComponentCriticality.MEDIUM)
                        .latencyMs(30.0)
                        .availability(99.5)
                        .loadQps(150.0)
                        .build())
                .addComponent(ComponentBuilder.of("analytics", "Analytics")
                        .type("WORKER")
                        .criticality(ComponentCriticality.LOW)
                        .latencyMs(180.0)
                        .availability(99.0)
                        .loadQps(300.0)
                        .build())

                .addDependency("web-gateway", "authentication", DependencyStrength.STRONG, DependencyType.SYNCHRONOUS_REST)
                .addDependency("web-gateway", "product-catalog", DependencyStrength.STRONG, DependencyType.SYNCHRONOUS_REST)
                .addDependency("product-catalog", "cart", DependencyStrength.MEDIUM, DependencyType.SYNCHRONOUS_REST)
                .addDependency("inventory", "cart", DependencyStrength.STRONG, DependencyType.SYNCHRONOUS_GRPC)
                .addDependency("cart", "checkout", DependencyStrength.STRONG, DependencyType.SYNCHRONOUS_REST)
                .addDependency("checkout", "payment", DependencyStrength.CRITICAL, DependencyType.SYNCHRONOUS_REST)
                .addDependency("checkout", "inventory", DependencyStrength.STRONG, DependencyType.SYNCHRONOUS_GRPC)
                .addDependency("payment", "order-service", DependencyStrength.MEDIUM, DependencyType.ASYNCHRONOUS_QUEUE)
                .addDependency("inventory", "order-service", DependencyStrength.STRONG, DependencyType.SYNCHRONOUS_GRPC)
                .addDependency("order-service", "notification", DependencyStrength.WEAK, DependencyType.ASYNCHRONOUS_QUEUE)
                .addDependency("order-service", "analytics", DependencyStrength.WEAK, DependencyType.ASYNCHRONOUS_QUEUE)
                .build();
    }
}
